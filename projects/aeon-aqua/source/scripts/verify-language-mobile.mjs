import {chromium} from '@playwright/test';
const base=process.argv[2]||'http://127.0.0.1:8088';
const browser=await chromium.launch({channel:'msedge',headless:true});
const errors=[];
try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/');
  await page.locator('[data-language="en"]').click();
  await page.waitForFunction(()=>document.documentElement.lang==='en' && !document.querySelector('.language-switch').hasAttribute('aria-busy'));
  if(!(await page.locator('#manifesto h1').textContent()).includes('Technology must serve humanity'))throw new Error('Home não traduzida');
  await page.screenshot({path:'docs/previews/site-english.png'});
  for(const path of ['manifesto.html','sobre.html','outros-projetos.html','arquivos-uteis.html','projetos-navais.html','naval.html','projects/aeon.html','projects/alpha.html','projects/include.html','projects/ml-learner.html','404.html']){
    await page.goto(base+'/'+path);
    await page.waitForFunction(()=>document.documentElement.lang==='en' && !document.querySelector('.language-switch').hasAttribute('aria-busy'));
    if(await page.locator('[data-language=en]').getAttribute('aria-pressed')!=='true')throw new Error('Idioma não persistiu: '+path);
    if(await page.locator('.header').count() && await page.locator('.header').evaluate(e=>e.scrollWidth>innerWidth))throw new Error('Cabeçalho ultrapassa tela');
    if(path==='manifesto.html' && !(await page.locator('.manifesto-body p').first().textContent()).startsWith('Automation'))throw new Error('Manifesto incompleto');
    console.log('Idioma persistente: '+path);
  }
  await page.goto(base+'/projetos-navais.html');
  await page.waitForFunction(()=>!document.querySelector('.language-switch').hasAttribute('aria-busy'));
  if(!(await page.locator('.point-propulsion').textContent()).includes('Propulsion'))throw new Error('Propulsão sem tradução');
  await page.locator('[data-language=pt]').click();
  if(!(await page.locator('.point-propulsion').textContent()).includes('Propuls'+String.fromCharCode(227)+'o'))throw new Error('Português não restaurado');
  await page.locator('input[name=nome]').fill('Language test');
  await page.locator('[data-language=en]').click();
  if(await page.locator('input[name=nome]').inputValue()!=='Language test')throw new Error('Troca de idioma apagou formulário');
  await page.goto(base+'/projects/aeon-aqua/');
  await page.waitForSelector('#viewport[data-model-status=ready][data-ship-status=ready]',{timeout:60000});
  await page.locator('[data-language=en]').click();
  await page.keyboard.down('KeyF');await page.waitForTimeout(250);
  if(Number((await page.locator('#power').textContent()).match(/[\d.]+/)[0])<5)throw new Error('Idioma bloqueou controle por teclado');
  await page.keyboard.up('KeyF');
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  const touchPage=await mobile.newPage();touchPage.on('pageerror',e=>errors.push(e.message));
  await touchPage.goto(base+'/projects/aeon-aqua/');
  await touchPage.waitForSelector('#viewport[data-model-status=ready][data-ship-status=ready]',{timeout:60000});
  await touchPage.locator('#touch-controls').waitFor({state:'visible'});
  if(await touchPage.locator('.left-panel').isVisible() || await touchPage.locator('.right-panel').isVisible())throw new Error('Painéis devem iniciar recolhidos');
  if(await touchPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Simulador ultrapassa tela');
  await touchPage.locator('[data-panel-button=mission]').tap();
  if(!await touchPage.locator('.left-panel').isVisible())throw new Error('Missão não abriu');
  await touchPage.locator('[data-panel-button=mission]').tap();
  const session=await mobile.newCDPSession(touchPage);
  const stick=await touchPage.locator('#depth-stick').boundingBox(),cutter=await touchPage.locator('#touch-cutter').boundingBox();
  const depth=()=>touchPage.locator('#depth').textContent();
  const before=await depth();
  const points=[{id:1,x:stick.x+stick.width/2,y:stick.y+stick.height-12},{id:2,x:cutter.x+cutter.width/2,y:cutter.y+cutter.height/2}];
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:points});
  await touchPage.waitForTimeout(850);
  if(await depth()===before)throw new Error('Joystick não alterou profundidade');
  if(await touchPage.locator('#touch-cutter').getAttribute('aria-pressed')!=='true')throw new Error('Toques simultâneos não acionaram cortador');
  await session.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  await touchPage.waitForTimeout(100);
  if(await touchPage.locator('#touch-cutter').getAttribute('aria-pressed')!=='false')throw new Error('Cortador ficou preso após cancelar toque');
  const knob=await touchPage.locator('#depth-stick .stick-knob').evaluate(e=>e.style.transform);
  if(knob!=='translate(-50%, -50%)' && knob!=='translate(-50%,-50%)')throw new Error('Joystick não retornou ao centro');
  const move=await touchPage.locator('#move-stick').boundingBox();
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:3,x:move.x+move.width/2,y:move.y+12}]});
  await touchPage.waitForTimeout(150);
  if(Number((await touchPage.locator('#power').textContent()).match(/[\d.]+/)[0])<5)throw new Error('Joystick de movimento não respondeu');
  await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await touchPage.waitForTimeout(100);
  if(Number((await touchPage.locator('#power').textContent()).match(/[\d.]+/)[0])!==0)throw new Error('Movimento ficou acionado após soltar');
  await touchPage.locator('[data-language=en]').tap();
  await touchPage.waitForFunction(()=>document.documentElement.lang==='en' && !document.querySelector('.language-switch').hasAttribute('aria-busy'));
  if(!(await touchPage.locator('#touch-cutter').textContent()).includes('CUT'))throw new Error('Toque não traduzido');
  await touchPage.screenshot({path:'docs/previews/simulador-mobile-en.png'});
  await touchPage.setViewportSize({width:844,height:390});
  await touchPage.waitForTimeout(200);
  if(await touchPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Overflow em paisagem');
  await touchPage.screenshot({path:'docs/previews/simulador-mobile-paisagem.png'});
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('OK: PT/EN em 13 páginas; toque simultâneo, cancelamento, idioma e layouts portrait/landscape.');
}finally{await browser.close();}
